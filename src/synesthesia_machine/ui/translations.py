"""Small, explicit English/French translation service for the desktop UI."""

# Translation entries intentionally preserve French typography and often mirror long source text.
# ruff: noqa: E501, RUF001

from __future__ import annotations

from enum import StrEnum
from typing import Any

from PySide6.QtCore import QCoreApplication, QTranslator


class UiLanguage(StrEnum):
    """The intentionally limited set of languages supported by the application."""

    ENGLISH = "en"
    FRENCH = "fr"


_current_language = UiLanguage.ENGLISH


class _FrenchQtTranslator(QTranslator):
    """Translate the small set of native standard-button labels used by the app."""

    def translate(
        self,
        context: str,
        source_text: str,
        disambiguation: str | None = None,
        n: int = -1,
    ) -> str:
        del context, disambiguation, n
        return _QT_FRENCH.get(source_text, "")

    def isEmpty(self) -> bool:
        return False


_qt_translator = _FrenchQtTranslator()


def set_language(language: UiLanguage) -> None:
    global _current_language
    _current_language = language
    application = QCoreApplication.instance()
    if application is None:
        return
    QCoreApplication.removeTranslator(_qt_translator)
    if language is UiLanguage.FRENCH:
        QCoreApplication.installTranslator(_qt_translator)


def current_language() -> UiLanguage:
    return _current_language


def tr(source: str) -> str:
    """Translate one authored English UI string, falling back to the source text."""

    if _current_language is UiLanguage.ENGLISH:
        return source
    return _FRENCH.get(source, source)


def trf(source: str, /, **values: Any) -> str:
    """Translate a format template before interpolating its named values."""

    return tr(source).format(**values)


